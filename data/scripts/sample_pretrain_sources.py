"""
Samples real pretraining-style raw text from four free, open, human-
authored sources, matching the same "fluency" role TinyStories plays
in the corpus but covering genuinely different registers: encyclopedic
(Wikipedia), literary (Gutenberg books), code (GitHub, permissive
licenses only), and general web text (C4). Each is truncated per-item
and capped at a target total size so no single source dominates --
same philosophy as capping TinyStories down earlier, just applied to
four new sources instead of rebalancing one.

Sources (all free, HF, single downloaded shard sampled from, nothing
AI-generated):
  - wikimedia/wikipedia (20231101.en)        -- real encyclopedia articles
  - sedthh/gutenberg_english                  -- real public-domain books
  - codeparrot/codeparrot-clean-valid         -- real deduped GitHub code,
    filtered to permissive licenses (mit/apache/bsd/isc), excludes
    autogenerated files
  - allenai/c4 (en)                           -- real filtered Common
    Crawl web text
"""
import json
import os
import random

import pyarrow.parquet as pq

BASE = os.path.join(os.path.dirname(__file__), "..", "raw")
PERMISSIVE_LICENSES = {"mit", "apache-2.0", "bsd-3-clause", "bsd-2-clause", "isc"}
random.seed(42)


def sample_text_column(path, column, max_item_chars, target_mb, out_name, filter_fn=None):
    t = pq.read_table(path, columns=[column] if filter_fn is None else None)
    rows = t.to_pylist()
    random.shuffle(rows)
    budget = target_mb * 1_000_000
    written = 0
    out_path = os.path.join(BASE, out_name)
    with open(out_path, "w") as f:
        for row in rows:
            if filter_fn and not filter_fn(row):
                continue
            text = (row[column] if isinstance(row, dict) else row).strip()
            if not text:
                continue
            text = text[:max_item_chars]
            f.write(text + "\n<|endoftext|>\n")
            written += len(text)
            if written >= budget:
                break
    print(f"{out_name}: {written/1e6:.1f} MB written -> {out_path}")


if __name__ == "__main__":
    sample_text_column(
        os.path.join(BASE, "wikipedia.parquet"), "text",
        max_item_chars=2200, target_mb=45, out_name="wikipedia_sample.txt",
    )
    sample_text_column(
        os.path.join(BASE, "gutenberg.parquet"), "TEXT",
        max_item_chars=35000, target_mb=45, out_name="gutenberg_sample.txt",
    )
    sample_text_column(
        os.path.join(BASE, "code.parquet"), "content",
        max_item_chars=3000, target_mb=40, out_name="code_sample.txt",
        filter_fn=lambda r: (r.get("license") in PERMISSIVE_LICENSES and not r.get("autogenerated")),
    )
    sample_text_column(
        os.path.join(BASE, "c4.parquet"), "text",
        max_item_chars=1500, target_mb=40, out_name="c4_sample.txt",
    )
