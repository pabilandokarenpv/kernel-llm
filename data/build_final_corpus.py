"""
Build Kernel AI's final merged training corpus — assembled from real,
free, open-source datasets plus our own synthetic distillation data.
Every source listed here is either a well-known free/open dataset or data
generated by us (via a free model, used only to create training examples,
never to answer users). Nothing in this corpus is a secret.

Sources:
  - TinyStories (free, HF: roneneldan/TinyStories)               — fluency
  - Dolly15k (free, HF: databricks/databricks-dolly-15k)          — instructions
  - OASST2 (free, HF: OpenAssistant/oasst2)                       — human conversations
  - CodeAlpaca-20k (free, HF: sahil2801/CodeAlpaca-20k)            — coding
  - GSM8K (free, HF: openai/gsm8k)                                 — math reasoning
  - our own Kernel-language execution-trace corpus (4,829 programs) — Kernel semantics
  - our own distilled data (general/coding/kernel_task/kernel_explain,
    generated via gpt-oss-120b, used only for training, never serving)
"""

import json
import os

BASE = os.path.dirname(__file__)
RAW = os.path.join(BASE, "raw")
DISTILLED = os.path.join(BASE, "distilled")
OUT_PATH = os.path.join(BASE, "kernel_ai_final_corpus.txt")


def load_jsonl(path):
    if not os.path.exists(path):
        print(f"  [skip] not found: {path}")
        return []
    out = []
    with open(path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                out.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return out


def pair_to_text(rec):
    instr = rec.get("instruction", "").strip()
    resp = rec.get("response", "").strip()
    ctx = rec.get("context", "").strip() if rec.get("context") else ""
    if not instr or not resp:
        return None
    if ctx:
        return f"### Instruction:\n{instr}\n\n### Context:\n{ctx}\n\n### Response:\n{resp}"
    return f"### Instruction:\n{instr}\n\n### Response:\n{resp}"


def main():
    sections = []
    counts = {}

    # TinyStories: raw stories, pure fluency text
    ts_path = os.path.join(RAW, "tinystories.txt")
    if os.path.exists(ts_path):
        with open(ts_path) as f:
            raw = f.read()
        stories = [s.strip() for s in raw.split("<|endoftext|>") if s.strip()][:-1]
        sections.extend(stories)
        counts["tinystories"] = len(stories)

    # Instruction-style datasets: dolly, oasst2, codealpaca, gsm8k, distilled
    sources = {
        "dolly": os.path.join(RAW, "dolly.jsonl"),
        "oasst2": os.path.join(RAW, "oasst2_pairs.jsonl"),
        "codealpaca": os.path.join(RAW, "codealpaca_pairs.jsonl"),
        "gsm8k": os.path.join(RAW, "gsm8k_pairs.jsonl"),
        "distilled_general": os.path.join(DISTILLED, "general.jsonl"),
        "distilled_coding": os.path.join(DISTILLED, "coding.jsonl"),
        "distilled_kernel_task": os.path.join(DISTILLED, "kernel_task.jsonl"),
        "distilled_kernel_explain": os.path.join(DISTILLED, "kernel_explain.jsonl"),
    }
    for name, path in sources.items():
        records = load_jsonl(path)
        n = 0
        for rec in records:
            text = pair_to_text(rec)
            if text:
                sections.append(text)
                n += 1
        counts[name] = n

    # Kernel execution-trace corpus (source + output)
    kernel_path = os.path.join(BASE, "corpus.jsonl")
    kernel_records = load_jsonl(kernel_path)
    n = 0
    for rec in kernel_records:
        source = rec.get("source", "").strip()
        output = rec.get("output", [])
        if not source:
            continue
        if len(output) > 40:
            output = output[:40] + ["... (truncated)"]
        output_str = "\n".join(str(o) for o in output) if output else "(no output)"
        text = f"### Instruction:\nWhat does this Kernel program print when run?\n\n### Kernel code:\n{source}\n\n### Response:\n{output_str}"
        sections.append(text)
        n += 1
    counts["kernel_execution_traces"] = n

    with open(OUT_PATH, "w") as out:
        for s in sections:
            out.write(s + "\n<|endoftext|>\n")

    total_chars = sum(len(s) for s in sections)
    print("=== Final corpus assembled ===")
    for name, n in counts.items():
        print(f"  {name}: {n}")
    print(f"  TOTAL examples: {len(sections)}")
    print(f"  TOTAL size: {total_chars/1e6:.1f} MB")
    print(f"  saved to: {OUT_PATH}")


if __name__ == "__main__":
    main()
